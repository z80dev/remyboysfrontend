import type { Rgb, Surface } from './surface'

/** A bitmap font: every glyph is a list of rows, `#` = ink, `+` = soft ink (anti-aliasing), anything else = blank. */
export type Font = { height: number; spacing: number; glyphs: Record<string, readonly string[]> }

/**
 * Draws `text` and returns the advance width. Unknown characters are skipped as 2px gaps.
 * `soft` colours the `+` pixels (defaults to `ink`).
 */
export function drawText(s: Surface, font: Font, text: string, x: number, y: number, ink: Rgb, soft = ink): number {
  let cx = x
  for (const ch of text) {
    const g = font.glyphs[ch]
    if (!g) {
      cx += 2
      continue
    }
    g.forEach((row, j) => {
      for (let i = 0; i < row.length; i++) {
        if (row[i] === '#') s.set(cx + i, y + j, ink)
        else if (row[i] === '+') s.set(cx + i, y + j, soft)
      }
    })
    cx += g[0].length + font.spacing
  }
  return cx - x - font.spacing
}

export function textWidth(font: Font, text: string): number {
  let w = 0
  for (const ch of text) w += (font.glyphs[ch]?.[0].length ?? 2 - font.spacing) + font.spacing
  return w - font.spacing
}

